import PDFDocument from "pdfkit";
import { postgresService } from "../../database/postgres";
import { HostelError, monthLabel, taka, toMoney } from "./hostel.common";

const RECEIPT_QUERY = `
  SELECT p.*, i.invoice_number, i.billing_month, i.student_name, i.hostel_name, i.building_name,
    i.room_number, i.seat_number, b.outstanding_amount, s.brand_name
  FROM hostel_payments p
  JOIN hostel_invoices i ON i.id = p.invoice_id
  JOIN hostel_invoice_balances b ON b.id = p.invoice_id
  LEFT JOIN hostel_rent_settings s ON s.institution_id = p.institution_id
  WHERE p.institution_id = $1 AND p.id = $2`;

export const renderReceiptPdf = async (
  institutionId: string,
  paymentId: string
): Promise<{ fileName: string; content: Buffer }> => {
  const { rows } = await postgresService.query(RECEIPT_QUERY, [institutionId, paymentId]);
  const row = rows[0];
  if (!row) throw new HostelError(404, "Payment not found.");

  const remaining = toMoney(row.outstanding_amount);
  const details: [string, string][] = [
    ["Receipt Number", row.receipt_number],
    ["Invoice Number", row.invoice_number],
    ["Student Name", row.student_name],
    ["Student ID", row.student_id],
    ["Building", `${row.hostel_name}, ${row.building_name}`],
    ["Room / Seat", `Room ${row.room_number}, Seat ${row.seat_number ?? "-"}`],
    ["Billing Month", monthLabel(row.billing_month)],
    ["Payment Amount", taka(toMoney(row.amount))],
    ["Payment Date", row.payment_date],
    ["Payment Method", row.method],
    [row.method === "bKash" ? "bKash Transaction ID" : "Transaction Reference", row.transaction_reference || "-"],
    ["Remaining Balance", taka(remaining)],
    ["Payment Status", row.status === "Reversed" ? "Reversed" : remaining > 0 ? "Partially Paid" : "Paid"],
  ];

  const content = await new Promise<Buffer>((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 56, info: { Title: `Receipt ${row.receipt_number}` } });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.font("Helvetica-Bold").fontSize(20).text(row.brand_name || "Hostel Office");
    doc.moveDown(0.3).font("Helvetica").fontSize(13).fillColor("#475569").text("Hostel Rent Payment Receipt");
    doc.moveDown(1.2);

    details.forEach(([label, value]) => {
      const y = doc.y;
      doc.font("Helvetica").fontSize(11).fillColor("#64748b").text(label, 56, y, { width: 190 });
      doc.font("Helvetica-Bold").fillColor("#0f172a").text(String(value), 250, y, { width: 290 });
      doc.moveDown(0.7);
    });

    if (row.status === "Reversed") {
      doc.moveDown().font("Helvetica-Bold").fillColor("#b91c1c").text(`This payment was reversed. Reason: ${row.reversal_reason}`, 56);
    }
    doc.moveDown(2).font("Helvetica").fontSize(9).fillColor("#64748b").text("This receipt was generated by the system.", 56);
    doc.end();
  });

  return { fileName: `${row.receipt_number}.pdf`, content };
};

// An invoice as a PDF, with its lines, adjustments and payments.
export const renderInvoicePdf = async (
  institutionId: string,
  invoiceId: string
): Promise<{ fileName: string; content: Buffer }> => {
  const { rows } = await postgresService.query(
    `SELECT b.*, s.brand_name FROM hostel_invoice_balances b
     LEFT JOIN hostel_rent_settings s ON s.institution_id = b.institution_id
     WHERE b.institution_id = $1 AND b.id = $2`,
    [institutionId, invoiceId]
  );
  const invoice = rows[0];
  if (!invoice) throw new HostelError(404, "Invoice not found.");

  const [items, adjustments, payments] = await Promise.all([
    postgresService.query("SELECT * FROM hostel_invoice_items WHERE invoice_id = $1 ORDER BY sort_order", [invoiceId]),
    postgresService.query("SELECT * FROM hostel_invoice_adjustments WHERE invoice_id = $1 ORDER BY created_at", [invoiceId]),
    postgresService.query("SELECT * FROM hostel_payments WHERE invoice_id = $1 AND status = 'Confirmed' ORDER BY created_at", [invoiceId]),
  ]);
  const lines = items.rows.length
    ? items.rows.map((row: any) => [row.description, `${Number(row.quantity)} x ${taka(toMoney(row.unit_price))}`, taka(toMoney(row.amount))])
    : [[invoice.title || `Hostel rent, ${monthLabel(invoice.billing_month)}`, "1", taka(toMoney(invoice.rent_amount))]];

  const content = await new Promise<Buffer>((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 56, info: { Title: `Invoice ${invoice.invoice_number}` } });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const row = (label: string, value: string, bold = false) => {
      const y = doc.y;
      doc.font("Helvetica").fontSize(10).fillColor("#64748b").text(label, 56, y, { width: 200 });
      doc.font(bold ? "Helvetica-Bold" : "Helvetica").fillColor("#0f172a").text(value, 260, y, { width: 280, align: "right" });
      doc.moveDown(0.5);
    };

    doc.font("Helvetica-Bold").fontSize(20).fillColor("#0f172a").text(invoice.brand_name || "Hostel Office");
    doc.font("Helvetica").fontSize(12).fillColor("#475569").text(`Invoice ${invoice.invoice_number}`);
    doc.moveDown();
    row("Student", `${invoice.student_name} (${invoice.student_id})`);
    row("Building / Room / Seat", `${invoice.hostel_name}, ${invoice.building_name}, Room ${invoice.room_number}, Seat ${invoice.seat_number ?? "-"}`);
    row("Category", invoice.category);
    row("Billing Period", monthLabel(invoice.billing_month));
    row("Invoice Date", new Date(invoice.created_at).toISOString().slice(0, 10));
    row("Due Date", invoice.due_date);
    doc.moveDown(0.5).font("Helvetica-Bold").fontSize(12).fillColor("#0f172a").text("Charges", 56);
    doc.moveDown(0.3);
    lines.forEach(([description, quantity, amount]: string[]) => row(`${description} (${quantity})`, amount));
    adjustments.rows.forEach((item: any) => row(`Adjustment: ${item.reason}`, taka(toMoney(item.amount))));
    row("Total Payable", taka(toMoney(invoice.amount_due)), true);
    payments.rows.forEach((item: any) => row(`Payment ${item.receipt_number} (${item.method}, ${item.payment_date})`, `- ${taka(toMoney(item.amount))}`));
    row("Remaining Balance", taka(toMoney(invoice.outstanding_amount)), true);
    doc.moveDown(2).font("Helvetica").fontSize(9).fillColor("#64748b").text("This invoice was generated by the system.", 56);
    doc.end();
  });
  return { fileName: `${invoice.invoice_number}.pdf`, content };
};
